    private void button1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_button1ActionPerformed
        // TODO add your handling code here:
        String pseudo = pseudo_tf.getText().trim();
        String email = email_tf.getText().trim();
        LocalDate dateNaiss = birthDate_dpk.getSelectedDate();
        String platforme = platforme_tf.getText().trim();

        if (!validateField()) return;

        try {
            Player player = new Player(pseudo, email, dateNaiss, platforme, tournois.getId());
            PlayerDao.addPlayerToTournament(player); // Pas d'équipe en solo !
            JOptionPane.showMessageDialog(this, "Participant ajouté avec succès !");
            vider();
        } catch (SQLException | ClassNotFoundException ex) {
            showError("Erreur : " + ex.getMessage());
            Logger.getLogger(AjoutParticipant.class.getName()).log(Level.SEVERE, null, ex);
        }

    }//GEN-LAST:event_button1ActionPerformed

