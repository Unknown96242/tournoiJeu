    private boolean validateField() {
        String pseudo = pseudo_tf.getText().trim();
        String email = email_tf.getText().trim();
        LocalDate birthDate = birthDate_dpk.getSelectedDate();
        String platforme = platforme_tf.getText().trim();

        if (pseudo.isEmpty()) {
            showError("Le pseudo est obligatoire.");
            return false;
        }
        if (email.isEmpty() || !email.contains("@")) {
            showError("L'email est obligatoire et doit être valide.");
            return false;
        }
        if (birthDate == null) {
            showError("La date de naissance est obligatoire.");
            return false;
        }
        if (platforme.isEmpty()) {
            showError("La plateforme est obligatoire.");
            return false;
        }
        return true;
    }

    private void showError(String msg) {
        JOptionPane.showMessageDialog(this, msg, "Erreur", JOptionPane.ERROR_MESSAGE);
    }

